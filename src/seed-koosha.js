function imageId(file, folder, alt) {
  const url = `/img/${folder}/${file}`;
  const found = get('SELECT id FROM media WHERE url = ?', [url]);
  if (found) return found.id;
  const r = run(
    'INSERT INTO media (filename, original_name, url, mime, size, alt) VALUES (?,?,?,?,?,?)',
    [file, file, url, 'image/jpeg', 0, alt]
  );
  return Number(r.lastInsertRowid);
}

